/*
    Variables, Data Types in Java.
*/

public class VarsAndDatatypes {
    public static void main(String[] args) {
        String name = "Peter Parker";
        int age = 18;
        double weight = 70.5;
        char grade = 'A';
        boolean isHappy = true;

        System.out.println("My name is " + name + ", I am "
         + age + " years old and I weight " + weight + " KG.");
        
        System.out.print("I got an " + grade + " in all my courses!\n");

        if (isHappy) {
            System.out.println("I am a Backend Engineer and I love what I do.");
        }
    }
}


